#!/usr/bin/env python3
"""Prepare, validate and deploy user configuration without running a desktop session."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

CONFIG_DIRS = ('hypr', 'waybar', 'kitty', 'swaync', 'quickshell', 'fastfetch', 'appearance')
RESOLUTIONS = {'preferred', '1920x1080', '2560x1440', '3072x1920', '3840x2160'}
REFRESH_RATES = {'60', '75', '90', '120', '144', '165', '240'}
SCALES = {'1', '1.5', '2'}
CURSOR_LINE = re.compile(r'^env\s*=\s*(?:XCURSOR|HYPRCURSOR)_(?:SIZE|THEME)\s*,.*$', re.M)


def read_preferences(home):
    path = home / '.config/appearance/preferences.json'
    if not path.is_file():
        return {}
    data = json.loads(path.read_text())
    if not isinstance(data, dict):
        raise ValueError(f'Expected an object: {path}')
    return data


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n')


def monitor_rule(value):
    name, resolution, refresh, scale = value.split('|')
    if name and not re.fullmatch(r'[A-Za-z0-9_.:-]+', name):
        raise ValueError('Invalid monitor name')
    if resolution not in RESOLUTIONS or scale not in SCALES:
        raise ValueError('Only the offered resolution and scale presets are allowed')
    if resolution == 'preferred':
        if refresh != 'auto':
            raise ValueError('Preferred mode selects its refresh rate automatically')
        mode = 'preferred'
    else:
        if refresh not in REFRESH_RATES:
            raise ValueError('Only the offered refresh rate presets are allowed')
        mode = f'{resolution}@{refresh}'
    return f'monitor = {name}, {mode}, auto, {scale}'


def ignore_generated(directory, names):
    return [name for name in names if name == '__pycache__' or name == 'backups'
            or name.endswith(('.so', '.pyc')) or '.bak' in name or '.before-' in name]


def prepare(args):
    root, stage, home = args.root.resolve(), args.stage.resolve(), args.target_home.resolve()
    if stage == home or stage == root or home in stage.parents or stage in home.parents:
        raise ValueError('Stage, repository and destination must be separate trees')
    rules = [monitor_rule(value) for value in args.monitor]
    if not rules:
        raise ValueError('At least one monitor rule is required')
    if all(value.split('|', 1)[0] for value in args.monitor):
        rules.append('monitor = , preferred, auto, 1')
    preferences = read_preferences(home)
    preferences['replace_cursor'] = args.cursor == 'true'
    saved = home / '.config/hypr/current-wallpaper'
    selected = Path(saved.read_text().strip()) if saved.is_file() and saved.read_text().strip() else None
    if selected is not None and not selected.is_file():
        selected = None
    wallpaper_dir = home / 'Pictures/wallpapers'
    if args.wallpapers == 'false':
        if selected is not None:
            wallpaper_dir = selected.parent
        elif preferences.get('wallpaper_dir') and Path(preferences['wallpaper_dir']).is_dir():
            wallpaper_dir = Path(preferences['wallpaper_dir'])
        elif shutil.which('xdg-user-dir'):
            env = os.environ.copy()
            env.update(HOME=str(home), XDG_CONFIG_HOME=str(home / '.config'))
            result = subprocess.run(['xdg-user-dir', 'PICTURES'], env=env, capture_output=True, text=True)
            if result.returncode == 0 and result.stdout.strip():
                candidate = Path(result.stdout.strip()) / 'wallpapers'
                if candidate.is_dir():
                    wallpaper_dir = candidate
    preferences['wallpaper_dir'] = str(wallpaper_dir)
    stage.mkdir(parents=True, exist_ok=True)
    for name in CONFIG_DIRS:
        shutil.copytree(root / name, stage / '.config' / name,
                        ignore=ignore_generated, symlinks=True)
    shutil.copytree(root / 'wlogout', stage / '.config/wlogout', symlinks=True)
    unit = stage / '.config/systemd/user/quickshell-desktop-session.target'
    unit.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(root / 'systemd/user/quickshell-desktop-session.target', unit)
    (stage / '.config/hypr/monitors.conf').write_text('# Generated by the installer.\n' + '\n'.join(rules) + '\n')
    config = stage / '.config/hypr/hyprland.conf'
    if args.cursor == 'false':
        previous = home / '.config/hypr/hyprland.conf'
        previous_cursor = CURSOR_LINE.findall(previous.read_text()) if previous.is_file() else []
        config.write_text(CURSOR_LINE.sub('', config.read_text()) + '\n' + '\n'.join(previous_cursor) + '\n')
    if args.battery == 'false':
        config = stage / '.config/waybar/config.jsonc'
        config.write_text(config.read_text().replace('        "battery",\n', ''))
    write_json(stage / '.config/appearance/preferences.json', preferences)
    qml = 'import QtQml\nQtObject {\n    readonly property string directory: ' + json.dumps(str(wallpaper_dir), ensure_ascii=False) + '\n}\n'
    (stage / '.config/quickshell/WallpaperSettings.qml').write_text(qml)
    if selected is not None:
        (stage / '.config/hypr/current-wallpaper').write_text(str(selected) + '\n')
    if args.wallpapers == 'true':
        shutil.copytree(root / 'Pictures/wallpapers', stage / 'Pictures/wallpapers', symlinks=True)
    ascii_dir = stage / '.local/share/fastfetch'
    ascii_dir.mkdir(parents=True, exist_ok=True)
    for source in (root / 'Pictures').glob('ascii_*.txt'):
        shutil.copy2(source, ascii_dir / source.name)
    write_json(stage / 'installation.json', {'battery': args.battery == 'true', 'cursor': args.cursor == 'true',
               'wallpapers': args.wallpapers == 'true', 'monitors': rules})
    print('Конфиги подготовлены; существующие файлы пока не изменены.')


def check_themes(args):
    roots = [args.stage, args.target_home or Path.home()]
    for kind, names in [('themes', ['Flat-Remix-GTK-Blue-Light', 'Flat-Remix-GTK-Blue-Dark']),
                        ('icons', ['Flat-Remix-Blue-Light', 'Flat-Remix-Blue-Dark'])]:
        paths = [Path('/usr/share') / kind, Path('/usr/local/share') / kind]
        for root in roots:
            paths.extend([root / ('.themes' if kind == 'themes' else '.icons'), root / '.local/share' / kind])
        if kind == 'icons' and args.cursor == 'true':
            names.append('Bibata-Modern-Ice')
        for name in names:
            if not any((path / name / 'index.theme').is_file() for path in paths):
                raise ValueError(f'Не установлена тема: {name}')


def deploy(args):
    stage, home, backup = args.stage.resolve(), args.target_home.resolve(), args.backup.resolve()
    if backup.exists():
        raise ValueError('Backup directory already exists; choose a new installation run')
    if stage == home or home in stage.parents or stage in home.parents:
        raise ValueError('Staging and destination trees must be independent')
    replacements = [Path('.config') / name for name in CONFIG_DIRS + ('wlogout',)]
    replacements.append(Path('.config/systemd/user/quickshell-desktop-session.target'))
    for top in ('.themes', '.icons'):
        if (stage / top).is_dir():
            replacements.extend(path.relative_to(stage) for path in (stage / top).iterdir())
    fonts = stage / '.local/share/fonts/rice-nerd-symbols'
    if fonts.exists():
        replacements.append(fonts.relative_to(stage))
    changes = []
    created = []
    try:
        backup.mkdir(parents=True)
        shutil.copy2(stage / 'installation.json', backup / 'installation.json')
        for relative in replacements:
            source, destination, saved = stage / relative, home / relative, backup / relative
            if not source.exists():
                raise ValueError(f'Missing staged file: {relative}')
            destination.parent.mkdir(parents=True, exist_ok=True)
            had_original = destination.exists() or destination.is_symlink()
            if had_original:
                saved.parent.mkdir(parents=True, exist_ok=True)
                shutil.move(str(destination), str(saved))
            changes.append((destination, saved, had_original))
            if source.is_dir():
                shutil.copytree(source, destination, symlinks=True)
            else:
                shutil.copy2(source, destination)
        for top in ('Pictures/wallpapers', '.local/share/fastfetch'):
            source = stage / top
            if not source.is_dir():
                continue
            for path in source.rglob('*'):
                if not path.is_file():
                    continue
                destination = home / path.relative_to(stage)
                if destination.exists() or destination.is_symlink():
                    continue
                destination.parent.mkdir(parents=True, exist_ok=True)
                created.append(destination)
                shutil.copy2(path, destination)
        write_json(backup / 'added-files.json', [str(path.relative_to(home)) for path in created])
        owned = []
        for destination, saved, had_original in changes:
            owned.append({'path': str(destination.relative_to(home)), 'had_original': had_original})
        added = []
        for path in created:
            with path.open('rb') as stream:
                checksum = hashlib.file_digest(stream, 'sha256').hexdigest()
            added.append({'path': str(path.relative_to(home)), 'sha256': checksum})
        write_json(backup / 'deployment.json', {'schema': 1, 'managed': owned, 'added': added})
    except BaseException:
        for path in reversed(created):
            path.unlink(missing_ok=True)
        for destination, saved, had_original in reversed(changes):
            if destination.is_dir() and not destination.is_symlink():
                shutil.rmtree(destination)
            elif destination.exists() or destination.is_symlink():
                destination.unlink()
            if had_original:
                shutil.move(str(saved), str(destination))
        print('Замена конфигов отменена; предыдущие файлы восстановлены.', file=sys.stderr)
        raise
    print(f'Конфиги установлены. Резервная копия: {backup}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    sub.add_parser('inventory')
    supported = sub.add_parser('supported')
    supported.add_argument('modes'); supported.add_argument('resolution'); supported.add_argument('refresh', type=float)
    prepare_parser = sub.add_parser('prepare')
    for name in ('root', 'stage', 'target-home'):
        prepare_parser.add_argument('--' + name, type=Path, required=True)
    for name in ('battery', 'cursor', 'wallpapers'):
        prepare_parser.add_argument('--' + name, choices=('true', 'false'), required=True)
    prepare_parser.add_argument('--monitor', action='append', required=True)
    deploy_parser = sub.add_parser('deploy')
    for name in ('stage', 'target-home', 'backup'):
        deploy_parser.add_argument('--' + name, type=Path, required=True)
    themes = sub.add_parser('check-themes')
    themes.add_argument('--stage', type=Path, required=True)
    themes.add_argument('--target-home', type=Path)
    themes.add_argument('--cursor', choices=('true', 'false'), required=True)
    args = parser.parse_args()
    if args.command == 'inventory':
        for screen in json.load(sys.stdin):
            if screen.get('disabled'):
                continue
            name = screen['name']
            if re.fullmatch(r'[A-Za-z0-9_.:-]+', name):
                print(name + '\t' + ';'.join(screen.get('availableModes', [])))
    elif args.command == 'supported':
        for mode in args.modes.split(';'):
            match = re.fullmatch(r'(\d+x\d+)@(\d+(?:\.\d+)?)Hz', mode)
            if match and match[1] == args.resolution and abs(float(match[2]) - args.refresh) < 1:
                return 0
        return 1
    elif args.command == 'prepare':
        prepare(args)
    elif args.command == 'check-themes':
        check_themes(args)
    else:
        deploy(args)
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (OSError, ValueError) as error:
        sys.exit(f'Ошибка настройки: {error}')
